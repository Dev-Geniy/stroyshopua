// добір товарів за правилом шаблону; cat — масив товарів каталогу {id, name, cat, av, qty, img}
function pick(p, cat) {
  const out = [], seen = new Set();
  p.pick.forEach(([cats, re, n]) => {
    const pool = cat.filter(x => x.av && cats.includes(x.cat) && (!re || re.test(String(x.name).toLowerCase())) && !seen.has(x.id))
      .sort((a, b) => (+b.qty || 0) - (+a.qty || 0));
    const names = {}; let k = 0;
    for (const x of pool) {
      if (out.length >= 400) break;
      const nm = String(x.name).replace(/\(.*?\)/g, '').trim();
      if ((names[nm] = (names[nm] || 0) + 1) > 2) continue;       // не більше 2 однакових моделей
      out.push(x); seen.add(x.id);
      if (++k >= n) break;
    }
  });
  return out;
}
// перші товари кожної групи — у «Популярне»
function featured(p, items) {
  const f = [];
  p.pick.forEach(([cats]) => { const x = items.find(y => cats.includes(y.cat) && !f.includes(y)); if (x) f.push(x); });
  items.forEach(x => { if (f.length < 8 && !f.includes(x)) f.push(x); });
  return f.slice(0, 8);
}
return { list: P, pick, featured };
